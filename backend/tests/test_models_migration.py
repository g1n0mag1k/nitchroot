"""ORM model import and Alembic migration smoke tests."""

from pathlib import Path

from app.models import (
    AlertDelivery,
    Merchant,
    ProbeResult,
    ReconDiscrepancy,
    WebhookEvent,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS_DIR = REPO_ROOT / "alembic" / "versions"


def test_orm_models_are_importable() -> None:
    """All five ORM models are importable from the models package."""
    assert Merchant.__tablename__ == "merchants"
    assert ProbeResult.__tablename__ == "probe_results"
    assert WebhookEvent.__tablename__ == "webhook_events"
    assert ReconDiscrepancy.__tablename__ == "recon_discrepancies"
    assert AlertDelivery.__tablename__ == "alert_deliveries"


def test_initial_migration_file_exists_and_is_non_empty() -> None:
    """Initial autogenerated migration is present with table definitions."""
    migration_files = sorted(MIGRATIONS_DIR.glob("*.py"))
    assert migration_files, "expected at least one Alembic revision file"

    initial_migration = migration_files[0].read_text(encoding="utf-8")
    assert initial_migration.strip()

    for table in (
        "merchants",
        "probe_results",
        "webhook_events",
        "recon_discrepancies",
        "alert_deliveries",
    ):
        assert table in initial_migration
